"""Generate sigmoid/tanh LUTs shared by RTL and firmware.
Index = int8 two's-complement byte of the requantised pre-activation, x = q/16 (range [-8, 8)).
Output = int8, scale 1/128: sigmoid -> [0,127], tanh -> [-127,127].
"""
import math

def q(i):
    return i - 256 if i >= 128 else i

def rnd(v):
    return math.floor(v + 0.5)

def clamp(v, lo, hi):
    return max(lo, min(hi, v))

SIG = [clamp(rnd(128.0 / (1.0 + math.exp(-q(i) / 16.0))), 0, 127) for i in range(256)]
TANH = [clamp(rnd(128.0 * math.tanh(q(i) / 16.0)), -127, 127) for i in range(256)]

def sv_fn(name, tab):
    lines = [f"function automatic logic [7:0] {name}(input logic [7:0] i);", "    case (i)"]
    for i, v in enumerate(tab):
        lines.append(f"        8'd{i}: {name} = 8'sd{v};" if v >= 0 else f"        8'd{i}: {name} = -8'sd{-v};")
    lines += ["        default: " + name + " = 8'd0;", "    endcase", "endfunction", ""]
    return "\n".join(lines)

def c_arr(name, tab):
    body = ",".join(str(v) for v in tab)
    return f"static const int8_t {name}[256] = {{{body}}};\n"

if __name__ == "__main__":
    import sys
    root = sys.argv[1] if len(sys.argv) > 1 else "."
    with open(f"{root}/rtl/lut_tables.svh", "w", newline="\n") as f:
        f.write("// generated by scripts/gen_lut.py - do not edit\n")
        f.write(sv_fn("lut_sig", SIG))
        f.write(sv_fn("lut_tanh", TANH))
    with open(f"{root}/fw/lut_tables.h", "w", newline="\n") as f:
        f.write("// generated by scripts/gen_lut.py - do not edit\n#ifndef LUT_TABLES_H\n#define LUT_TABLES_H\n#include <stdint.h>\n")
        f.write(c_arr("LUT_SIG", SIG))
        f.write(c_arr("LUT_TANH", TANH))
        f.write("#endif\n")
    print("LUTs written")
