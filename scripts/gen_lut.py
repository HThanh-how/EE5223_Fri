# Sinh cùng LUT sigmoid/tanh cho RTL và C, chỉ số là byte INT8 theo two's complement.
# Chạy: python3 scripts/gen_lut.py . (dấu chấm chọn thư mục gốc đầu ra).
"""Generate sigmoid/tanh LUTs shared by RTL and firmware.
Index = int8 two's-complement byte of the requantised pre-activation, x = q/16 (range [-8, 8)).
Output = int8, scale 1/128: sigmoid -> [0,127], tanh -> [-127,127].
"""
# CLI: python3 scripts/gen_lut.py [root], mặc định root="."; thư mục rtl/fw phải có.
# Output ghi đè root/rtl/lut_tables.svh và root/fw/lut_tables.h, không in bảng ra stdout.
# Cùng một SIG/TANH sinh hai ngôn ngữ để firmware và RTL có giá trị bit-exact.
# Không có zero-point offset: input q có scale 1/16, output scale 1/128.
import math

# i là địa chỉ unsigned 0..255; decode two's complement thành q=-128..127.
# Thứ tự bảng 0..127 rồi -128..-1, không sắp từ số âm tới số dương.
def q(i):
    return i - 256 if i >= 128 else i

# floor(v+0.5) khớp quy ước làm tròn về phía dương tại điểm giữa.
def rnd(v):
    return math.floor(v + 0.5)

def clamp(v, lo, hi):
    return max(lo, min(hi, v))

# SIG[i]=clamp(floor(128/(1+exp(-q/16))+0.5),0,127).
# TANH[i]=clamp(floor(128*tanh(q/16)+0.5),-127,127).
# Điểm dương gần 1 bị clamp 127 để vẫn là signed INT8, không wrap thành -128.
# Tanh không xuất -128 theo miền clamp đã chọn, dù input có thể là -128.
SIG = [clamp(rnd(128.0 / (1.0 + math.exp(-q(i) / 16.0))), 0, 127) for i in range(256)]
TANH = [clamp(rnd(128.0 * math.tanh(q(i) / 16.0)), -127, 127) for i in range(256)]

# Sinh case đầy đủ 256 địa chỉ byte; hằng âm viết dạng -8'sdK cho cú pháp SV.
# Default=0 chỉ là nhánh dự phòng; mọi địa chỉ 8 bit đã có một entry.
def sv_fn(name, tab):
    lines = [f"function automatic logic [7:0] {name}(input logic [7:0] i);", "    case (i)"]
    for i, v in enumerate(tab):
        lines.append(f"        8'd{i}: {name} = 8'sd{v};" if v >= 0 else f"        8'd{i}: {name} = -8'sd{-v};")
    lines += ["        default: " + name + " = 8'd0;", "    endcase", "endfunction", ""]
    return "\n".join(lines)

# Mảng const int8_t[256] được truy cập bằng uint8_t để số âm thành index đúng.
def c_arr(name, tab):
    body = ",".join(str(v) for v in tab)
    return f"static const int8_t {name}[256] = {{{body}}};\n"

if __name__ == "__main__":
    import sys
    # Khi chỉ import SIG/TANH từ quantize.py, nhánh main không chạy nên không ghi file.
    # newline="\n" giữ format output ổn định để preflight diff kiểm tái lập từng byte.
    root = sys.argv[1] if len(sys.argv) > 1 else "."
    with open(f"{root}/rtl/lut_tables.svh", "w", newline="\n") as f:
        f.write("// generated by scripts/gen_lut.py - do not edit\n")
        f.write(sv_fn("lut_sig", SIG))
        f.write(sv_fn("lut_tanh", TANH))
    with open(f"{root}/fw/lut_tables.h", "w", newline="\n") as f:
        f.write("// generated by scripts/gen_lut.py - do not edit\n#ifndef LUT_TABLES_H\n#define LUT_TABLES_H\n#include <stdint.h>\n")
        f.write(c_arr("LUT_SIG", SIG))
        f.write(c_arr("LUT_TANH", TANH))
        f.write("#endif\n")
    print("LUTs written")
